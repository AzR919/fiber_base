"""
Writers for everything setup_encode.py produces besides the downloads:
  - <encode_root>/<cell>/manifest.json  which assays the cell folder holds (read at runtime)
  - data_prep/encode_lock.yaml          the exact ENCODE file chosen per cell + assay (reproducibility)
  - configs/metapaths.yaml              fiber paths + cell folders, consumed by the training/eval code
"""

import datetime
import json
import os

import yaml

OUTPUT_SUFFIX = {"fold change over control": "fc", "signal p-value": "pval"}


def track_filename(assay, file_accession, output_type):
    suffix = OUTPUT_SUFFIX.get(output_type, output_type.replace(" ", "_"))
    return f"{assay}_{file_accession}_{suffix}.bigWig"


def _now():
    return datetime.datetime.now().isoformat(timespec="seconds")


def _atomic_write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def _dump(data):
    # Block style only: sections are concatenated into one file, and a flow-style top-level
    # mapping ({a: 1, b: 2}) followed by block sections is invalid YAML.
    return yaml.safe_dump(data, default_flow_style=False, sort_keys=False, width=1000).rstrip()


def read_manifest(cell_dir):
    path = os.path.join(cell_dir, "manifest.json")
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def write_manifest(cell_dir, cell, cell_spec, spec, tracks):
    """tracks: {assay: selection dict (incl. 'filename')} for the files present in cell_dir."""
    assays = {}
    for assay, sel in tracks.items():
        assay_spec = spec["assays"][assay]
        assays[assay] = {
            "file": sel["filename"],
            "file_accession": sel["file"],
            "experiment": sel["experiment"],
            "assay_title": assay_spec["assay_title"],
            "target": assay_spec.get("target"),
            "biological_replicates": sel["biological_replicates"],
            "md5sum": sel["md5sum"],
            "file_size": sel["file_size"],
            "url": sel["url"],
            "audit": sel["audit"],
        }
    manifest = {
        "cell": cell,
        "encode_term_name": cell_spec["term_name"],
        "assembly": spec["assembly"],
        "output_type": spec["output_type"],
        "generated": _now(),
        "assays": assays,
        "missing": [a for a in spec["assays"] if a not in tracks],
    }
    _atomic_write(os.path.join(cell_dir, "manifest.json"), json.dumps(manifest, indent=2) + "\n")


def write_lock(path, plan):
    """plan: {cell: {assay: selection}}. Edit an entry to pin a different file; delete it to re-select."""
    lock = {
        cell: {
            assay: {
                "file": sel["file"],
                "experiment": sel["experiment"],
                "md5sum": sel["md5sum"],
                "audit": sel["audit"],
                "date_released": sel["date_released"],
            }
            for assay, sel in tracks.items()
        }
        for cell, tracks in plan.items()
    }
    header = ("# GENERATED by data_prep/setup_encode.py: the ENCODE file used for each cell line + assay.\n"
              "# Re-runs reuse these choices so the data stays fixed. To pin a different file, edit its accession\n"
              "# (and experiment); to let the script choose again, delete the entry or run with --reselect.\n"
              f"# Last written: {_now()}\n\n")
    _atomic_write(path, header + _dump(lock) + "\n")


def write_metapaths(path, spec, spec_path, cell_assays):
    """cell_assays: {cell folder name: list of assays whose file is present in that folder}."""
    assay_names = list(spec["assays"])
    fiber_paths = {s: os.path.join(spec["fiber_dir"], f) for s, f in spec["fiber_samples"].items()}

    cell_types = {}
    for cell, cell_spec in spec["encode_cells"].items():
        if not cell_assays.get(cell):
            continue  # nothing downloaded for this line: not usable for training
        for sample in cell_spec["fiber_samples"]:
            cell_types[sample] = os.path.join(spec["encode_root"], cell)

    status = {}
    for cell in spec["encode_cells"]:
        have = cell_assays.get(cell, [])
        status[cell] = {
            "complete": len(have) == len(assay_names),
            "available": [a for a in assay_names if a in have],
            "missing": [a for a in assay_names if a not in have],
        }

    sections = [
        "# GENERATED by data_prep/setup_encode.py from " + spec_path + " — do not edit by hand.",
        "# Regenerate with: python data_prep/setup_data.py  (or sbatch data_prep/slurm_setup_data.sh)",
        "# Reference genome / cCREs / train-val chromosomes are in configs/reference.yaml (merged in by load_metapaths).",
        f"# Generated: {_now()}",
        "",
        f"# Bulk targets are ENCODE '{spec['output_type']}' bigWigs ({spec['assembly']}).",
        _dump({"encode_output_type": spec["output_type"], "assembly": spec["assembly"]}),
        "",
        "# Fiber-seq sample -> CRAM. Every sample is listed, with or without ENCODE data.",
        _dump({"fiber_paths": fiber_paths}),
        "",
        "# Fiber-seq sample -> ENCODE folder of its cell line. At runtime the folder's manifest.json says which",
        "# assays exist; requested assays a cell lacks are masked out of the loss. Samples without ENCODE data",
        "# are not listed here (fiber_paths only).",
        _dump({"cell_types": cell_types}),
        "",
        "# Informational only (runtime reads the manifests): which assays each ENCODE cell folder has.",
        _dump({"assay_status": status}),
        "",
    ]
    _atomic_write(path, "\n".join(sections))
